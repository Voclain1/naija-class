// Response
// ---------------------------------------------------------------------------

export type StudentIntakeStatus = "PENDING" | "COMPLETED" | "EXPIRED";

export interface StudentIntakeRowDto {
  /** Index into the `students` array that was prepared. */
  index: number;
  /** The values that will be written, as the server normalised them. */
  values: Omit<IntakeStudentRow, "dateOfBirth" | "admittedAt"> & { dateOfBirth: string; admittedAt?: string };
  /** The typed number, or null when one is assigned at confirmation. */
  admissionNumber: string | null;
  /** ASSIGNED_ON_CONFIRM: the number is not reserved and is not shown in advance. */
  admissionNumberSource: "TYPED" | "ASSIGNED_ON_CONFIRM";
  errors: IntakeRowProblem<IntakeRowErrorCode>[];
  warnings: IntakeRowProblem<IntakeRowWarningCode>[];
}

export interface StudentIntakeOutcomeDto {
  createdCount: number;
  enrolledCount: number;
  /** One entry per prepared row, in row order. */
  students: { index: number; studentId: string; admissionNumber: string; enrollmentId: string | null }[];
}

export interface StudentIntakeProposalDto {
  id: string;
  status: StudentIntakeStatus;
  /** Send this back to confirm. Changes whenever anything the preview shows changes. */
  previewHash: string;
  expiresAt: string;
  createdAt: string;
  confirmedAt: string | null;
  placement:
    | { mode: "ENROL"; termId: string; classArmId: string; termLabel: string | null; classLabel: string | null }
    | { mode: "DEFER" };
  counts: { rows: number; withErrors: number; withWarnings: number; assignedOnConfirm: number };
  batchErrors: IntakeBatchProblem<IntakeBatchErrorCode>[];
  batchWarnings: IntakeBatchProblem<IntakeBatchWarningCode>[];
  /** PENDING, not expired, and no errors anywhere. */
  canConfirm: boolean;
  /**
   * The rows, while the proposal is PENDING. Empty once COMPLETED or EXPIRED:
   * the row data is cleared then (`dataCleared`), and the outcome remains.
   */
  rows: StudentIntakeRowDto[];
  dataCleared: boolean;
  duplicateRule: string;
  outcome: StudentIntakeOutcomeDto | null;
}

/** 409 codes the confirm can answer with. Each leaves nothing written. */
export const STUDENT_INTAKE_CONFLICT_CODES = {
  /** previewHash does not match this proposal. Re-read it (GET) and review again. */
  previewMismatch: "INTAKE_PREVIEW_MISMATCH",
  /** Something the preview showed has changed. POST …/refresh, review, confirm the new one. */
  stale: "INTAKE_PREVIEW_STALE",
  /** Past expiresAt. POST …/refresh. */
  expired: "INTAKE_EXPIRED",
  /** The preview has errors. Fix the rows and prepare again. */
  blocked: "INTAKE_BLOCKED",
  /** A concurrent write collided (e.g. a typed number taken a moment ago). Nothing saved; refresh. */
  retry: "INTAKE_RETRY",
  /** Refresh of a proposal that was already confirmed. Read its outcome instead. */
  alreadyConfirmed: "INTAKE_ALREADY_CONFIRMED",
  /** clientRequestId reused with a different request. */
  requestIdReused: "INTAKE_REQUEST_ID_REUSED",
} as const;
