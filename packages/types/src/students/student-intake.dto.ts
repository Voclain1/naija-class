import { z } from "zod";

import { MAX_BULK_STUDENTS } from "./bulk-create-students.dto.js";
import { createStudentSchema } from "./create-student.dto.js";

// Reviewed student intake (2026-11-09, docs/modules/student-intake-proposals.md).
//
// Three steps, all server-owned:
//   1. PREPARE  POST /student-intake/proposals            -> a proposal and its preview
//   2. CONFIRM  POST /student-intake/proposals/:id/confirm -> the outcome (exactly once)
//   3. RECOVER  GET  /student-intake/proposals/:id         -> status and outcome at any time
// plus REFRESH (POST /student-intake/proposals/:id/refresh) when a preview is
// stale or expired. No model is involved anywhere in this flow.

export const STUDENT_INTAKE_KIND = "student-intake";

/** Minutes a prepared proposal can be confirmed for. */
export const STUDENT_INTAKE_TTL_MINUTES = 30;

/** One batch, the same limit as POST /students/bulk. */
export const MAX_STUDENT_INTAKE_ROWS = MAX_BULK_STUDENTS;

/**
 * Where the batch goes. Always explicit: there is no default class and no
 * default term, and "place later" is a choice the person makes (DEFER), never
 * what an absent field means.
 */
export const intakePlacementSchema = z.discriminatedUnion("mode", [
  z.object({ mode: z.literal("ENROL"), termId: z.string().uuid(), classArmId: z.string().uuid() }).strict(),
  z.object({ mode: z.literal("DEFER") }).strict(),
]);
export type IntakePlacement = z.infer<typeof intakePlacementSchema>;

/** A row is exactly a bulk-add row: no enrolment of its own, no guardians. */
export const intakeStudentRowSchema = createStudentSchema.omit({ enrollment: true });
export type IntakeStudentRow = z.infer<typeof intakeStudentRowSchema>;

export const prepareStudentIntakeSchema = z
  .object({
    /**
     * Generated by the client once per batch (a UUID) and reused on every
     * retry of the same prepare. The same id with the same rows returns the
     * same proposal; the same id with different rows is refused (409
     * INTAKE_REQUEST_ID_REUSED).
     */
    clientRequestId: z.string().uuid(),
    placement: intakePlacementSchema,
    students: z.array(intakeStudentRowSchema).min(1).max(MAX_STUDENT_INTAKE_ROWS),
  })
  .strict();
export type PrepareStudentIntakeInput = z.infer<typeof prepareStudentIntakeSchema>;

export const confirmStudentIntakeSchema = z
  .object({
    /** The `previewHash` of the preview the person reviewed. */
    previewHash: z.string().regex(/^[0-9a-f]{64}$/),
  })
  .strict();
export type ConfirmStudentIntakeInput = z.infer<typeof confirmStudentIntakeSchema>;

export const refreshStudentIntakeSchema = z
  .object({
    /** A new UUID for the new proposal, reused on retries of this refresh. */
    clientRequestId: z.string().uuid(),
  })
  .strict();
export type RefreshStudentIntakeInput = z.infer<typeof refreshStudentIntakeSchema>;

// ---------------------------------------------------------------------------
// Problems. An ERROR blocks confirmation; a WARNING is shown and does not.
// ---------------------------------------------------------------------------

export const INTAKE_ROW_ERROR_CODES = [
  /** The same typed number appears on more than one row of the batch. */
  "ADMISSION_NUMBER_REPEATED",
  /** The typed number already belongs to a student of this school. */
  "ADMISSION_NUMBER_TAKEN",
  /** Blank number, and the school types its own numbers. */
  "ADMISSION_NUMBER_REQUIRED",
  /** Blank number, the school numbers per class, and the batch has no class. */
  "ADMISSION_NUMBER_NEEDS_CLASS",
] as const;
export type IntakeRowErrorCode = (typeof INTAKE_ROW_ERROR_CODES)[number];

export const INTAKE_ROW_WARNING_CODES = [
  /** Same first name, last name and date of birth as a student on the roll. */
  "POSSIBLE_DUPLICATE_ON_ROLL",
  /** Same first name, last name and date of birth as another row. */
  "POSSIBLE_DUPLICATE_IN_BATCH",
  "DATE_OF_BIRTH_IN_FUTURE",
] as const;
export type IntakeRowWarningCode = (typeof INTAKE_ROW_WARNING_CODES)[number];

export const INTAKE_BATCH_ERROR_CODES = [
  "TERM_NOT_FOUND",
  "CLASS_ARM_NOT_FOUND",
  "CLASS_ARM_INACTIVE",
  /** PLAN_ENFORCEMENT=enforce and the batch would pass the plan's cap. */
  "PLAN_STUDENT_LIMIT",
  /** The school's automatic format no longer parses; fix it in Settings. */
  "ADMISSION_FORMAT_INVALID",
] as const;
export type IntakeBatchErrorCode = (typeof INTAKE_BATCH_ERROR_CODES)[number];

export const INTAKE_BATCH_WARNING_CODES = [
  /** The class has a capacity and the batch would take it past it. */
  "CLASS_OVER_CAPACITY",
  /** The chosen term is not the school's current term. */
  "TERM_NOT_CURRENT",
] as const;
export type IntakeBatchWarningCode = (typeof INTAKE_BATCH_WARNING_CODES)[number];

export interface IntakeRowProblem<C extends string> {
  code: C;
  message: string;
  /** Other rows involved (repeats, in-batch duplicates), by index. */
  relatedIndexes?: number[];
  /** Students on the roll involved (possible duplicates), opaque ids only. */
  relatedStudentIds?: string[];
}

export interface IntakeBatchProblem<C extends string> {
  code: C;
  message: string;
  details?: Record<string, number | string>;
}

/** The disclosed rule behind the advisory duplicate warnings. */
export const INTAKE_DUPLICATE_RULE =
  "Possible duplicate: same first name, last name and date of birth as another row or a student " +
  "already on the roll (any status), ignoring case, accents and spacing. Advisory only: nothing " +
  "is merged and the row is still added if you confirm.";

