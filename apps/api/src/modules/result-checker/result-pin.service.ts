import { randomInt } from "node:crypto";

import { Inject, Injectable } from "@nestjs/common";

import { Prisma, withTenant } from "@school-kit/db";
import {
  ConflictError,
  NotFoundError,
  RESULT_PIN_DIGITS,
  type GenerateResultPinBatchInput,
  type GeneratedResultPinBatchDto,
  type ResultPinBatchDto,
  type ResultPinBatchListResponse,
} from "@school-kit/types";

import type { AuthContext } from "../../common/auth/auth-context";
import { assertUserActiveAndHasOneOf } from "../../common/auth/role-check";
import { RESULT_PIN_KEY, formatPin, hashPin, normalisePin } from "./result-pin-key";

// Result Checker PINs (Phase 8c / CP6b, docs/modules/phase-8.md §21.3–21.4).
//
// Batches are generated by the school and sold offline (D9, D10), scoped to one
// term (D15). The plaintext PINs leave this service exactly once, in the
// return value of generateBatch (D16); only HMACs are stored (D56).
//
// redeem() is the ONE redemption path — the public checker and both portals
// call it — so the rules about terms, binding and uses cannot drift between
// surfaces.

type TenantDb = Parameters<Parameters<typeof withTenant>[1]>[0];

interface RequestContext {
  ipAddress: string | null;
  userAgent: string | null;
}

export type RedeemVia = "CHECKER" | "GUARDIAN" | "STUDENT";

/**
 * Why a redemption was refused. Internal: each caller decides how much of it
 * to say. The public checker says almost none of it (§21.5); a signed-in
 * family is told enough to act on.
 */
export type RedeemRefusal =
  | "NOT_RELEASED" // no RELEASED card for this student and term
  | "PIN_INVALID" // malformed, unknown, or voided (the PIN or its batch)
  | "PIN_WRONG_TERM" // the batch is for another term (D15)
  | "PIN_OTHER_STUDENT" // bound to another student (D10)
  | "PIN_USED_UP"; // bound to this student, no uses left (D57)

export class RedeemRefusedError extends Error {
  constructor(readonly reason: RedeemRefusal) {
    super(reason);
  }
}

export type RedeemOutcome =
  /** The card is FREE: nothing to unlock and no use taken. */
  | { kind: "free" }
  /** Already unlocked on a portal; no use taken (D57). */
  | { kind: "already-unlocked" }
  /** A use was taken; `usesLeft` after it. */
  | { kind: "redeemed"; usesLeft: number };

const AUDIT = {
  generate: "result-pin.batch-generate",
  voidBatch: "result-pin.batch-void",
  voidPin: "result-pin.void",
  redeem: "result-pin.redeem",
} as const;

const MAX_GENERATE_ATTEMPTS = 3;

@Injectable()
export class ResultPinService {
  constructor(@Inject(RESULT_PIN_KEY) private readonly key: string) {}

  // POST /result-pins/batches — owner/admin.
  async generateBatch(
    authCtx: AuthContext,
    input: GenerateResultPinBatchInput,
    reqCtx: RequestContext,
  ): Promise<GeneratedResultPinBatchDto> {
    await assertUserActiveAndHasOneOf(authCtx, ["owner", "admin"]);

    // A collision with an existing PIN is astronomically unlikely (10^12
    // space), but the unique index is the guarantee, so a collision retries
    // the whole batch with fresh PINs rather than failing the school.
    for (let attempt = 1; ; attempt++) {
      try {
        return await this.generateOnce(authCtx, input, reqCtx);
      } catch (e) {
        const collided = e instanceof Prisma.PrismaClientKnownRequestError && e.code === "P2002";
        if (!collided || attempt >= MAX_GENERATE_ATTEMPTS) throw e;
      }
    }
  }

  private generateOnce(
    authCtx: AuthContext,
    input: GenerateResultPinBatchInput,
    reqCtx: RequestContext,
  ): Promise<GeneratedResultPinBatchDto> {
    return withTenant(authCtx.schoolId, async (db) => {
      const term = await db.term.findUnique({
        where: { id: input.termId },
        select: { id: true, name: true, academicYearId: true, academicYear: { select: { label: true } } },
      });
      if (!term) throw new NotFoundError("Term not found.");

      // Serialise batch numbering per school for this transaction, so two
      // admins generating at once cannot take the same number.
      await db.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${`result-pin-batch:${authCtx.schoolId}`}))`;
      const last = await db.resultPinBatch.findFirst({ orderBy: { number: "desc" }, select: { number: true } });
      const number = (last?.number ?? 0) + 1;

      const batch = await db.resultPinBatch.create({
        data: {
          schoolId: authCtx.schoolId,
          academicYearId: term.academicYearId,
          termId: term.id,
          number,
          size: input.quantity,
          maxUses: input.maxUses,
          createdBy: authCtx.userId,
        },
      });

      const seen = new Set<string>();
      const pins: { serial: string; digits: string }[] = [];
      while (pins.length < input.quantity) {
        const digits = randomDigits();
        if (seen.has(digits)) continue;
        seen.add(digits);
        pins.push({ serial: `B${number}-${String(pins.length + 1).padStart(4, "0")}`, digits });
      }

      await db.resultPin.createMany({
        data: pins.map((p) => ({
          schoolId: authCtx.schoolId,
          batchId: batch.id,
          serial: p.serial,
          pinHash: hashPin(this.key, p.digits),
        })),
      });

      // Never a PIN in the audit row — only what was made.
      await this.audit(db, authCtx, reqCtx, AUDIT.generate, batch.id, {
        batchNumber: number,
        termId: term.id,
        size: input.quantity,
        maxUses: input.maxUses,
      });

      return {
        batch: {
          id: batch.id,
          number,
          termId: term.id,
          termName: term.name,
          academicYearLabel: term.academicYear.label,
          size: batch.size,
          maxUses: batch.maxUses,
          redeemedCount: 0,
          voidedCount: 0,
          createdAt: batch.createdAt,
          voidedAt: null,
        },
        pins: pins.map((p) => ({ serial: p.serial, pin: formatPin(p.digits) })),
      };
    });
  }

  // GET /result-pins/batches — owner/admin. Counts only; never a PIN.
  async listBatches(authCtx: AuthContext): Promise<ResultPinBatchListResponse> {
    await assertUserActiveAndHasOneOf(authCtx, ["owner", "admin"]);

    return withTenant(authCtx.schoolId, async (db) => {
      const batches = await db.resultPinBatch.findMany({ orderBy: { number: "desc" } });
      if (batches.length === 0) return { data: [] };

      const ids = batches.map((b) => b.id);
      const [terms, redeemed, voided] = await Promise.all([
        db.term.findMany({
          where: { id: { in: [...new Set(batches.map((b) => b.termId))] } },
          select: { id: true, name: true, academicYear: { select: { label: true } } },
        }),
        db.resultPin.groupBy({
          by: ["batchId"],
          where: { batchId: { in: ids }, boundStudentId: { not: null } },
          _count: { _all: true },
        }),
        db.resultPin.groupBy({
          by: ["batchId"],
          where: { batchId: { in: ids }, voidedAt: { not: null } },
          _count: { _all: true },
        }),
      ]);
      const termById = new Map(terms.map((t) => [t.id, t]));
      const redeemedBy = new Map(redeemed.map((r) => [r.batchId, r._count._all]));
      const voidedBy = new Map(voided.map((r) => [r.batchId, r._count._all]));

      return {
        data: batches.map(
          (b): ResultPinBatchDto => ({
            id: b.id,
            number: b.number,
            termId: b.termId,
            termName: termById.get(b.termId)?.name ?? "",
            academicYearLabel: termById.get(b.termId)?.academicYear.label ?? "",
            size: b.size,
            maxUses: b.maxUses,
            redeemedCount: redeemedBy.get(b.id) ?? 0,
            voidedCount: voidedBy.get(b.id) ?? 0,
            createdAt: b.createdAt,
            voidedAt: b.voidedAt,
          }),
        ),
      };
    });
  }

  // POST /result-pins/batches/:id/void — owner/admin. Unlocks a voided PIN
  // already made stand: the family paid for them.
  async voidBatch(authCtx: AuthContext, batchId: string, reqCtx: RequestContext): Promise<{ voided: true }> {
    await assertUserActiveAndHasOneOf(authCtx, ["owner", "admin"]);

    return withTenant(authCtx.schoolId, async (db) => {
      const batch = await db.resultPinBatch.findUnique({ where: { id: batchId }, select: { id: true, voidedAt: true, number: true } });
      if (!batch) throw new NotFoundError("PIN batch not found.");
      if (batch.voidedAt) throw new ConflictError("PIN_BATCH_ALREADY_VOIDED", "This batch has already been voided.");

      await db.resultPinBatch.update({
        where: { id: batchId },
        data: { voidedAt: new Date(), voidedBy: authCtx.userId },
      });
      await this.audit(db, authCtx, reqCtx, AUDIT.voidBatch, batchId, { batchNumber: batch.number });
      return { voided: true };
    });
  }

  // POST /result-pins/void — owner/admin, one card by its printed serial.
  async voidPin(authCtx: AuthContext, serial: string, reqCtx: RequestContext): Promise<{ voided: true }> {
    await assertUserActiveAndHasOneOf(authCtx, ["owner", "admin"]);
    const normalised = serial.trim().toUpperCase();

    return withTenant(authCtx.schoolId, async (db) => {
      const pin = await db.resultPin.findFirst({ where: { serial: normalised }, select: { id: true, voidedAt: true } });
      if (!pin) throw new NotFoundError("No PIN has that serial number.");
      if (pin.voidedAt) throw new ConflictError("PIN_ALREADY_VOIDED", "That PIN has already been voided.");

      await db.resultPin.update({ where: { id: pin.id }, data: { voidedAt: new Date() } });
      await this.audit(db, authCtx, reqCtx, AUDIT.voidPin, pin.id, { serial: normalised });
      return { voided: true };
    });
  }

  /**
   * Redeem a PIN for one student's term (§21.4). Runs in the CALLER's tenant
   * transaction, so the caller's following read through ReleasedResultsService
   * sees the unlock this writes.
   *
   * The checker takes a use on every successful call (D57). A portal takes one
   * only to create the unlock; once the term is unlocked it takes none.
   */
  async redeem(
    db: TenantDb,
    args: {
      schoolId: string;
      studentId: string;
      termId: string;
      pin: string;
      via: RedeemVia;
      /** Who did it, for the audit row: a guardian, a student, or null on the public checker. */
      actorId: string | null;
      ipAddress: string | null;
    },
  ): Promise<RedeemOutcome> {
    const card = await db.reportCard.findFirst({
      where: { studentId: args.studentId, termId: args.termId, status: "RELEASED" },
      select: { accessMode: true },
    });
    if (!card) throw new RedeemRefusedError("NOT_RELEASED");
    if (card.accessMode !== "PIN") return { kind: "free" };

    if (args.via !== "CHECKER") {
      const unlocked = await db.resultUnlock.findFirst({
        where: { studentId: args.studentId, termId: args.termId },
        select: { id: true },
      });
      if (unlocked) return { kind: "already-unlocked" };
    }

    const digits = normalisePin(args.pin);
    if (!digits) throw new RedeemRefusedError("PIN_INVALID");

    const pin = await db.resultPin.findFirst({
      where: { pinHash: hashPin(this.key, digits) },
      select: {
        id: true,
        serial: true,
        uses: true,
        boundStudentId: true,
        boundAt: true,
        voidedAt: true,
        batch: { select: { termId: true, maxUses: true, voidedAt: true } },
      },
    });
    if (!pin || pin.voidedAt || pin.batch.voidedAt) throw new RedeemRefusedError("PIN_INVALID");
    if (pin.batch.termId !== args.termId) throw new RedeemRefusedError("PIN_WRONG_TERM");
    if (pin.boundStudentId && pin.boundStudentId !== args.studentId) {
      throw new RedeemRefusedError("PIN_OTHER_STUDENT");
    }

    // Take the use with a CONDITIONAL update, so two checks racing for the
    // last use cannot both win, and two students racing for an unbound card
    // cannot both bind it. Zero rows means one of the two conditions lost.
    const taken = await db.resultPin.updateMany({
      where: {
        id: pin.id,
        voidedAt: null,
        uses: { lt: pin.batch.maxUses },
        OR: [{ boundStudentId: null }, { boundStudentId: args.studentId }],
      },
      data: {
        uses: { increment: 1 },
        boundStudentId: args.studentId,
        boundAt: pin.boundAt ?? new Date(),
      },
    });
    if (taken.count === 0) {
      const now = await db.resultPin.findUniqueOrThrow({ where: { id: pin.id }, select: { boundStudentId: true } });
      throw new RedeemRefusedError(
        now.boundStudentId && now.boundStudentId !== args.studentId ? "PIN_OTHER_STUDENT" : "PIN_USED_UP",
      );
    }

    // D17: one unlock per student-term, whoever made it first.
    await db.resultUnlock.upsert({
      where: { schoolId_studentId_termId: { schoolId: args.schoolId, studentId: args.studentId, termId: args.termId } },
      create: {
        schoolId: args.schoolId,
        studentId: args.studentId,
        termId: args.termId,
        pinId: pin.id,
        via: args.via,
      },
      update: {},
    });

    const usesLeft = pin.batch.maxUses - (pin.uses + 1);
    await db.auditLog.create({
      data: {
        schoolId: args.schoolId,
        userId: args.actorId,
        action: AUDIT.redeem,
        entityType: "result_pin",
        entityId: pin.id,
        ipAddress: args.ipAddress,
        metadata: {
          serial: pin.serial,
          studentId: args.studentId,
          termId: args.termId,
          via: args.via,
          usesLeft,
        } satisfies Prisma.InputJsonValue,
      },
    });
    return { kind: "redeemed", usesLeft };
  }

  private async audit(
    db: TenantDb,
    authCtx: AuthContext,
    reqCtx: RequestContext,
    action: string,
    entityId: string,
    metadata: Prisma.InputJsonValue,
  ): Promise<void> {
    await db.auditLog.create({
      data: {
        schoolId: authCtx.schoolId,
        userId: authCtx.userId,
        action,
        entityType: "result_pin",
        entityId,
        ipAddress: reqCtx.ipAddress,
        metadata,
      },
    });
  }
}

/** 12 uniformly random digits from the CSPRNG; a leading zero is fine. */
function randomDigits(): string {
  let out = "";
  for (let i = 0; i < RESULT_PIN_DIGITS; i++) out += String(randomInt(10));
  return out;
}
